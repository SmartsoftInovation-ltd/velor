const mongoose = require("mongoose");
const { connectTestDb, clearTestDb, disconnectTestDb } = require("../helpers/db");
const { runForTenant } = require("../../src/tenancy/context");

jest.mock("../../src/config/redis.config", () => require("../mocks/redisCache"));

const CrateTransaction = require("../../src/models/crateTransaction.model");
const PurchaseReturn = require("../../src/models/purchaseReturn.model");
const SalesReturn = require("../../src/models/salesReturn.model");

// The Day Cash Summary sits directly under the Inflow and Outflow feeds on the
// dashboard, so its two figures have to be the same money those feeds add up:
//   Total Receive Today = Inflow grand total (today)
//   Total Payment Today = Outflow grand total (today)
// They drifted because Day Cash counted every cash transaction — including the
// auto-generated rows each module writes — and left purchase/sales returns out
// entirely. This pins the two rules that keep them equal.
describe("day cash summary parity with the inflow/outflow feeds", () => {
  const tenantId = new mongoose.Types.ObjectId();

  beforeAll(connectTestDb);
  afterEach(clearTestDb);
  afterAll(disconnectTestDb);

  const today = () => new Date();

  const txn = (extra) =>
    runForTenant(tenantId, () =>
      CrateTransaction.create({
        date: today(),
        account: new mongoose.Types.ObjectId(),
        amount: 100,
        ...extra,
      }),
    );

  // The filters the Day Cash receive/payment totals apply, mirrored from the
  // Inflow and Outflow boxes.
  const MANUAL_RECEIVE = {
    transactionType: "cash recived",
    saleReference: null,
    customerPaymentReference: null,
    customerAdvancePaymentReference: null,
    purchaseReturnReference: null,
  };
  const MANUAL_PAYMENT = {
    transactionType: "cash payment",
    purchaseReference: null,
    supplierPaymentReference: null,
    salesReturnReference: null,
  };

  const sum = (match) =>
    runForTenant(tenantId, async () => {
      const [row] = await CrateTransaction.aggregate([
        { $match: match },
        { $group: { _id: null, amount: { $sum: "$amount" } } },
      ]);
      return row?.amount || 0;
    });

  it("counts a hand-typed cash receipt once", async () => {
    await txn({ transactionType: "cash recived", amount: 500 });
    expect(await sum(MANUAL_RECEIVE)).toBe(500);
  });

  // Each of these rows belongs to a module that is already its own source in
  // the totals, so counting the row too would double that money.
  it.each([
    "saleReference",
    "customerPaymentReference",
    "customerAdvancePaymentReference",
    "purchaseReturnReference",
  ])("skips a cash receipt generated by %s", async (field) => {
    await txn({ transactionType: "cash recived", amount: 500, [field]: new mongoose.Types.ObjectId() });
    expect(await sum(MANUAL_RECEIVE)).toBe(0);
  });

  it.each(["purchaseReference", "supplierPaymentReference", "salesReturnReference"])(
    "skips a cash payment generated by %s",
    async (field) => {
      await txn({ transactionType: "cash payment", amount: 500, [field]: new mongoose.Types.ObjectId() });
      expect(await sum(MANUAL_PAYMENT)).toBe(0);
    },
  );

  it("keeps the manual entry when auto-generated rows sit beside it", async () => {
    await txn({ transactionType: "cash recived", amount: 500 });
    // Only the fields the receive side filters on: a "cash recived" row tagged
    // with a payment-side reference is not something any module writes.
    for (const field of Object.keys(MANUAL_RECEIVE).filter((k) => k !== "transactionType")) {
      await txn({ transactionType: "cash recived", amount: 900, [field]: new mongoose.Types.ObjectId() });
    }
    expect(await sum(MANUAL_RECEIVE)).toBe(500);
  });

  // Returns are their own source on each side; Day Cash used to omit them, so
  // a refund never reached the day's figures at all.
  it("dates purchase returns on returnDate, the field the Inflow box ranges on", async () => {
    await runForTenant(tenantId, () =>
      PurchaseReturn.collection.insertOne({
        serial: "PURR-TEST-1",
        totalReturnAmount: 250,
        returnDate: today(),
        tenantId,
        createdAt: today(),
        updatedAt: today(),
      }),
    );

    const total = await runForTenant(tenantId, async () => {
      const [row] = await PurchaseReturn.aggregate([
        { $match: { returnDate: { $gte: new Date(Date.now() - 3600e3), $lte: new Date(Date.now() + 3600e3) } } },
        { $group: { _id: null, amount: { $sum: "$totalReturnAmount" } } },
      ]);
      return row?.amount || 0;
    });
    expect(total).toBe(250);
  });

  it("dates sales returns on date, the field the Outflow box ranges on", async () => {
    await runForTenant(tenantId, () =>
      SalesReturn.collection.insertOne({
        returnId: "RET-TEST-1",
        totalReturnAmount: 325,
        date: today(),
        tenantId,
        createdAt: today(),
        updatedAt: today(),
      }),
    );

    const total = await runForTenant(tenantId, async () => {
      const [row] = await SalesReturn.aggregate([
        { $match: { date: { $gte: new Date(Date.now() - 3600e3), $lte: new Date(Date.now() + 3600e3) } } },
        { $group: { _id: null, amount: { $sum: "$totalReturnAmount" } } },
      ]);
      return row?.amount || 0;
    });
    expect(total).toBe(325);
  });
});
